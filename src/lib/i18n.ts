export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const s: string = (lang === "mr" && mr[key]) || en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** "9 am" or "सकाळी 9": Marathi names the part of the day instead of am/pm. */
export function hourLabel(lang: Lang, h: number): string {
  const n = h % 12 || 12;
  if (lang === "en") return `${n} ${h < 12 ? "am" : "pm"}`;
  const part = h < 5 ? "पहाटे" : h < 12 ? "सकाळी" : h < 16 ? "दुपारी" : h < 20 ? "संध्याकाळी" : "रात्री";
  return `${part} ${n}`;
}

/** A slot's time window in the shopper's language, derived from its start/end, not its stored English label. */
export function slotText(lang: Lang, slot: Pick<Slot, "id" | "start" | "end">): string {
  const from = ist(slot.start).h;
  if (slot.id.startsWith("pickup-")) return lang === "en" ? `Ready by ${hourLabel("en", from)}` : `${hourLabel("mr", from)} पर्यंत ready`;
  const to = ist(slot.end).h;
  if (lang === "en") return `${hourLabel("en", from)} – ${hourLabel("en", to)}`;
  // "सकाळी 9 – 11", or "सकाळी 11 – दुपारी 1" when the part of the day changes
  const a = hourLabel("mr", from);
  const b = hourLabel("mr", to);
  return a.split(" ")[0] === b.split(" ")[0] ? `${a} – ${to % 12 || 12}` : `${a} – ${b}`;
}

/** "Today" / "Tomorrow" / a date, in the shopper's language. */
export function dayText(lang: Lang, slot: Pick<Slot, "date" | "start">, now = Date.now()): string {
  if (slot.date === istDateKey(now)) return translate(lang, "day.today");
  if (slot.date === istDateKey(now + 86_400_000)) return translate(lang, "day.tomorrow");
  return new Date(slot.start).toLocaleDateString(lang === "mr" ? "mr-IN-u-nu-latn" : "en-IN", { weekday: "short", day: "numeric", month: "short", timeZone: "Asia/Kolkata" });
}

